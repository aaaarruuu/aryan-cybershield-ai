"""Generate documentation/ML_EVALUATION.md from REAL runs (EDA, model metrics, log-detection check).
Usage (repo root, venv active):  python scripts/ml_report.py
Nothing in the output is hand-written: every number is computed here."""
import json, os, sys, tempfile
from collections import Counter
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
tmp = tempfile.mkdtemp()
os.environ.update(DATABASE_URL=f"sqlite:///{tmp}/r.db", CHROMA_PATH=f"{tmp}/c", SECRET_KEY="report-secret-key-0123456789-abcdefghijklmn")
sys.path.insert(0, os.path.join(ROOT, "backend"))
import pandas as pd
from app.ml import phishing_model as pm
from app.ml.log_analysis import analyse
from app.services.log_parser import parse_upload
from app.services import phishing as ph

df = pd.read_csv(pm.SYNTH_CSV)
hand = json.load(open(pm.HAND_JSON))
rep = pm.train()
out = ["# ML Evaluation Report (auto-generated)", "", "Generated by `scripts/ml_report.py`. All numbers below were computed by that script.", "",
       "## 1. Dataset (EDA)", "", f"* Training corpus: `{pm.SYNTH_CSV.name}` - **synthetic, template-generated** (see `scripts/generate_sample_data.py`).",
       f"* Rows: {len(df)} (after de-duplication used for training: {rep['train_rows'] + rep['heldout_split']['n']})",
       f"* Class balance: {dict(Counter(df['label']))}", f"* Text length (chars): mean {df['text'].str.len().mean():.0f}, min {df['text'].str.len().min()}, max {df['text'].str.len().max()}",
       f"* Distinct texts: {df['text'].nunique()} of {len(df)} - a small template space, so train/test overlap in *style* is unavoidable.", ""]
pipe = pm.load_model(); vec, clf = pipe.named_steps["tfidf"], pipe.named_steps["clf"]
terms = vec.get_feature_names_out(); coef = clf.coef_[0]
top_p = [terms[i] for i in coef.argsort()[-10:][::-1]]; top_l = [terms[i] for i in coef.argsort()[:10]]
out += ["Most phishing-indicative terms (logistic-regression weights): " + ", ".join(f"`{t}`" for t in top_p), "",
        "Most legitimate-indicative terms: " + ", ".join(f"`{t}`" for t in top_l), "",
        "## 2. Features & model", "", "* Text: TF-IDF (unigrams+bigrams, min_df=2, sublinear tf) -> Logistic Regression (class_weight=balanced, seed 42).",
        "* Deterministic features (not learned): sender look-alike, risky TLD, URL structure, urgency/credential/threat language, auth results (see `services/phishing.py`).",
        "* Final verdict = deterministic points + at most 25 ML points; ML alone can never yield `phishing`.", "",
        "## 3. Phishing text model", ""]
def row(n, m): return f"| {n} | {m['n']} | {m['accuracy']} | {m['precision']} | {m['recall']} | {m['f1']} | {m['false_positive_rate']} | TN {m['confusion_matrix']['tn']} FP {m['confusion_matrix']['fp']} FN {m['confusion_matrix']['fn']} TP {m['confusion_matrix']['tp']} |"
out += ["| Evaluation set | n | Accuracy | Precision | Recall | F1 | FPR | Confusion |", "|---|---|---|---|---|---|---|---|",
        row("Synthetic held-out (75/25 stratified)", rep["heldout_split"]), row("Hand-written (never trained on)", rep["handwritten_eval"]), "",
        "**Interpretation.** The synthetic held-out score is near-perfect because train and test come from the same templates; it is *not* evidence of real-world accuracy. "
        "The 16-email hand-written set is a more honest but tiny check (wide uncertainty). Misclassified: " + "; ".join(f"\"{m}...\"" for m in rep['handwritten_eval']['misclassified']) + ".", ""]
# end-to-end analyser (deterministic + ML) on the same hand-written set
tp = fp = tn = fn = 0; wrong = []
for r in hand:
    c = ph.analyse(subject="", sender="", body=r["text"], urls=[])["classification"]
    pred = c != "legitimate"; truth = r["label"] == "phishing"
    tp += pred and truth; fp += pred and not truth; tn += (not pred) and (not truth); fn += (not pred) and truth
    if pred != truth: wrong.append(r["text"][:60])
out += ["## 4. Full phishing analyser (deterministic + ML), body text only", "",
        f"On the same 16 hand-written texts (no sender/URL supplied, 'suspicious' counted as flagged): TP {tp}, FP {fp}, TN {tn}, FN {fn}. Errors: " + ("; ".join(wrong) or "none") + ".", ""]
# log detection on the synthetic sample with known injected scenarios
p = parse_upload("auth_logs.csv", open(os.path.join(ROOT, "sample_data", "auth_logs.csv"), "rb").read())
r = analyse(p.events); rules = [a for a in r["alerts"] if a["source"] == "rule"]; ml = [a for a in r["alerts"] if a["source"] == "ml"]
expected = {"brute_force": "203.0.113.45", "password_spraying": "198.51.100.77", "sensitive_activity_off_hours": None}
found = {k: any(a["type"] == k and (v is None or a["src_ip"] == v) for a in rules) for k, v in expected.items()}
benign_rule_hits = [a for a in rules if a["src_ip"] and a["src_ip"].startswith("10.0.") and a["type"] in ("brute_force", "password_spraying")]
out += ["## 5. Log detection on the synthetic sample (known ground truth)", "",
        f"Sample: {r['summary']['events']} events, 3 injected attack scenarios (brute force + success, password spraying, off-hours privileged activity) among ~220 normal events.", "",
        "| Injected scenario | Detected by rules |", "|---|---|"] + [f"| {k} | {'yes' if v else 'NO'} |" for k, v in found.items()] + [
        "", f"* Rule alerts: {len(rules)}; false brute-force/spraying alerts on normal internal traffic: {len(benign_rule_hits)}.",
        f"* Isolation Forest windows flagged: {r['ml_meta'].get('flagged_windows')} of {r['ml_meta'].get('windows')} (contamination fixed at 5%), producing {len(ml)} low-severity ML alerts. "
        "Because contamination is a fixed fraction, the model **always** flags ~5% of windows - these are anomaly *signals*, expected to include benign activity, and are labelled unconfirmed in reports.", "",
        "**Caveat.** The scenarios were generated by the same author as the detection rules, so this is a functional check, not an accuracy benchmark. "
        "No evaluation on CIC-IDS2017, UNSW-NB15 or other public datasets was performed (see LIMITATIONS.md).", ""]
open(os.path.join(ROOT, "documentation", "ML_EVALUATION.md"), "w").write("\n".join(out))
print("\n".join(out))
